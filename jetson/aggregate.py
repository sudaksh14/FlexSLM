#!/usr/bin/env python3
"""Tables from the Jetson results (runs anywhere; no GPU, no torch).

    python3 jetson/aggregate.py --results ~/mednest-results \
        --cluster mednest:8=results/gen.hf_export-flexllama__sft.paper.qwen3_0p6b_nested-level8.t32.samples.jsonl ...

Writes <results>/derived/: widths.csv / widths.tex (one row per model and power mode), switch.csv,
trace.csv / trace.tex, agreement.csv. --cluster TARGET[:LEVEL]=SAMPLES joins the on-device answers
with the cluster's per-question outputs of the same model (results/gen.*.samples.jsonl, test-file
order) by test_index: the share of subset questions scored the same way on both (the board must
reproduce the evaluated model; bf16 kernels may flip a few borderline answers).
"""
import argparse
import csv
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nestbench.results import load_results  # noqa: E402

BENCH = ["MedQA", "MCQA", "HeadQA", "Calc", "Bullets", "Pro-H", "XpertQA"]


def _g(d, *ks):
    for k in ks:
        d = (d or {}).get(k) if isinstance(d, dict) else None
    return d


def _f(x, nd=1):
    return "--" if x is None else f"{x:.{nd}f}"


def load(pattern):
    out = []
    for path in sorted(glob.glob(pattern)):
        prov, rows = load_results(path)
        mode = _g(prov, "device", "power_mode", "name") or _g(prov, "device", "power_mode", "id")
        for r in rows:
            r["_file"], r["_power_mode"] = os.path.basename(path), mode
        out += rows
    return out


def widths_table(rows, out):
    summ = [r for r in rows if r.get("kind") == "summary"]
    cols = ["power_mode", "target", "level", "params_M", "weights_GB", "peak_sys_mem_GB", "ttft_ms", "decode_ms_tok",
            "answer_ms_median", "answer_ms_p95", "energy_net_J", "energy_gross_J", "acc_avg"] + BENCH + ["n", "throttled"]
    table = []
    for s in summ:
        table.append({
            "power_mode": s["_power_mode"], "target": s["target"], "level": s.get("level"),
            "params_M": (s.get("params") or 0) / 1e6, "weights_GB": (s.get("weight_bytes_width") or 0) / 1e9,
            "peak_sys_mem_GB": (s.get("peak_sys_mem_mb") or 0) / 1024,
            "ttft_ms": _g(s, "ttft_ms", "median"), "decode_ms_tok": _g(s, "ms_per_decode_token", "median"),
            "answer_ms_median": _g(s, "total_ms", "median"), "answer_ms_p95": _g(s, "total_ms", "p95"),
            "energy_net_J": s.get("energy_net_j_per_answer"), "energy_gross_J": s.get("energy_gross_j_per_answer"),
            "acc_avg": _g(s, "accuracy", "Avg"), **{b: _g(s, "accuracy", b) for b in BENCH},
            "n": s["n"], "throttled": s.get("throttled")})
    with open(os.path.join(out, "widths.csv"), "w", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=cols)
        wr.writeheader()
        wr.writerows(table)
    with open(os.path.join(out, "widths.tex"), "w") as f:
        f.write("% generated by jetson/aggregate.py\n\\begin{tabular}{@{}llrrrrrrrr@{}}\n\\toprule\n"
                "Mode & Model & Params (M) & Peak mem (GB) & TTFT (ms) & ms/token & Answer (ms) & p95 (ms) "
                "& Energy (J) & Acc.\\ (subset) \\\\\n\\midrule\n")
        for t in table:
            name = f"MedNest L{t['level']}" if t["target"] == "mednest" else t["target"]
            f.write(f"{t['power_mode']} & {name} & {_f(t['params_M'], 0)} & {_f(t['peak_sys_mem_GB'], 2)} & "
                    f"{_f(t['ttft_ms'], 0)} & {_f(t['decode_ms_tok'], 1)} & {_f(t['answer_ms_median'], 0)} & "
                    f"{_f(t['answer_ms_p95'], 0)} & {_f(t['energy_net_J'], 2)} & {_f(t['acc_avg'], 1)} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    return table


def switch_table(rows, out):
    keep = [r for r in rows if r.get("kind") in ("switch_summary", "load", "memory")]
    flat = []
    for r in keep:
        flat.append({"kind": r["kind"], "path": r.get("path"), "level": r.get("level"), "cache": r.get("cache"),
                     "switch_ms_median": _g(r, "switch_ms", "median"),
                     "ttft_after_switch_ms": _g(r, "ttft_after_switch_ms", "median"),
                     "ttft_repeat_ms": _g(r, "ttft_repeat_ms", "median"), "load_ms": r.get("load_ms"),
                     "load_plus_first_ms": r.get("load_plus_first_ms"),
                     "weight_GB": (r.get("weight_bytes") or r.get("weight_bytes_resident") or r.get("elastic_resident_bytes") or 0) / 1e9,
                     "all_separate_GB": (r.get("all_separate_resident_bytes") or 0) / 1e9 or None,
                     "all_9_separate_GB": (r.get("all_9_separate_bytes_computed") or 0) / 1e9 or None})
    if flat:
        with open(os.path.join(out, "switch.csv"), "w", newline="") as f:
            wr = csv.DictWriter(f, fieldnames=list(flat[0]))
            wr.writeheader()
            wr.writerows(flat)
    return flat


def trace_table(rows, out):
    summ = [r for r in rows if r.get("kind") == "policy_summary"]
    if not summ:
        return []
    cols = ["policy", "n", "miss_rate", "miss_rate_urgent", "accuracy", "latency_median_ms", "latency_p95_ms",
            "energy_j_per_answer", "switches", "switch_ms_total", "capture_ms_total", "levels_used"]
    table = [{"policy": s["policy"], "n": s["n"], "miss_rate": s["miss_rate"], "miss_rate_urgent": s["miss_rate_urgent"],
              "accuracy": s["accuracy"], "latency_median_ms": _g(s, "latency_ms", "median"),
              "latency_p95_ms": _g(s, "latency_ms", "p95"), "energy_j_per_answer": s.get("energy_j_per_answer"),
              "switches": s["switches"], "switch_ms_total": s["switch_ms_total"],
              "capture_ms_total": s.get("capture_ms_total"),
              "levels_used": json.dumps(s["levels_used"])} for s in summ]
    with open(os.path.join(out, "trace.csv"), "w", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=cols)
        wr.writeheader()
        wr.writerows(table)
    with open(os.path.join(out, "trace.tex"), "w") as f:
        f.write("% generated by jetson/aggregate.py\n\\begin{tabular}{@{}lrrrrrr@{}}\n\\toprule\n"
                "Policy & Missed (\\%) & Missed urgent (\\%) & Acc.\\ (\\%) & Median (ms) & Energy (J) & Switches \\\\\n\\midrule\n")
        for t in table:
            f.write(f"{t['policy']} & {_f(100 * t['miss_rate'])} & {_f(None if t['miss_rate_urgent'] is None else 100 * t['miss_rate_urgent'])} & "
                    f"{_f(t['accuracy'])} & {_f(t['latency_median_ms'], 0)} & {_f(t['energy_j_per_answer'], 2)} & {t['switches']} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    return table


def agreement(rows, specs, out):
    res = []
    answers = [r for r in rows if r.get("kind") == "answer"]
    for spec in specs:
        key, _, path = spec.partition("=")
        target, _, level = key.partition(":")
        cluster = [json.loads(l) for l in open(path)]
        mine = [r for r in answers if r["target"] == target and (not level or r.get("level") == int(level))]
        both = [(r["correct"], cluster[r["test_index"]]["correct"]) for r in mine if r.get("test_index") is not None]
        if not both:
            continue
        res.append({"target": target, "level": level or None, "n": len(both),
                    "same_score": sum(a == b for a, b in both) / len(both),
                    "acc_device": 100 * sum(a for a, _ in both) / len(both),
                    "acc_cluster_same_questions": 100 * sum(b for _, b in both) / len(both)})
    if res:
        with open(os.path.join(out, "agreement.csv"), "w", newline="") as f:
            wr = csv.DictWriter(f, fieldnames=list(res[0]))
            wr.writeheader()
            wr.writerows(res)
    return res


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--results", default=os.environ.get("MEDNEST_OUT", os.path.expanduser("~/mednest-results")))
    p.add_argument("--cluster", action="append", default=[], help="TARGET[:LEVEL]=cluster samples.jsonl")
    args = p.parse_args()
    out = os.path.join(args.results, "derived")
    os.makedirs(out, exist_ok=True)
    wrows = load(os.path.join(args.results, "widths*.jsonl"))
    t = widths_table(wrows, out)
    s = switch_table(load(os.path.join(args.results, "switch*.jsonl")), out)
    tr = trace_table(load(os.path.join(args.results, "trace*.jsonl")), out)
    a = agreement(wrows, args.cluster, out)
    print(f"widths rows {len(t)}, switch rows {len(s)}, trace policies {len(tr)}, agreement rows {len(a)} -> {out}")
    for r in a:
        print(f"  {r['target']} L{r['level']}: same score on {r['same_score']:.1%} of {r['n']} questions "
              f"(device {r['acc_device']:.1f} vs cluster {r['acc_cluster_same_questions']:.1f})")


if __name__ == "__main__":
    main()
